package labWork;

public class whileLoopDemo {

	public static void main(String[] args) {
		// Program that prints all even #s between 1 & 20 using a while loop
		
		int i = 2;
		
		System.out.println("Even numbers from 1-20: ");
		while (i <= 20) {
			System.out.print(i + " ");
			i+=2;
		}

	}

}
